"""Generate Android launcher icons, splash screens and web icons for both Flutter apps
from the brand pack in assets/brand/ (source: mishwar_brand_assets.zip).

Usage (from the repo root):  python scripts/generate_brand_assets.py
Requires Pillow (pip install pillow). Re-run whenever the brand assets change.
"""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
BRAND = ROOT / "assets" / "brand"
APPS = ["customer_app", "driver_app"]

# Sampled from 09_splash_dark / 05_app_icon_dark: navy gradient, top -> bottom.
BG_TOP = (2, 18, 42)
BG_BOTTOM = (3, 30, 63)
SPLASH_BG_HEX = "#02122A"

DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}

APP_ICON = Image.open(BRAND / "05_app_icon_dark_1024.png").convert("RGBA")
SYMBOL = Image.open(BRAND / "07_app_icon_foreground_transparent.png").convert("RGBA")
LOGO = Image.open(BRAND / "01_logo_transparent_for_dark.png").convert("RGBA")


def gradient(width: int, height: int) -> Image.Image:
    img = Image.new("RGBA", (width, height))
    draw = ImageDraw.Draw(img)
    for y in range(height):
        t = y / max(1, height - 1)
        color = tuple(round(a + (b - a) * t) for a, b in zip(BG_TOP, BG_BOTTOM)) + (255,)
        draw.line([(0, y), (width, y)], fill=color)
    return img


def trimmed(img: Image.Image) -> Image.Image:
    """Crop transparent margins."""
    return img.crop(img.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox())


def fit_center(content: Image.Image, canvas_px: int, content_fraction: float, background=None) -> Image.Image:
    """Scale content so its larger side is content_fraction of the canvas, centered."""
    canvas = background.copy() if background is not None else Image.new("RGBA", (canvas_px, canvas_px), (0, 0, 0, 0))
    scale = canvas_px * content_fraction / max(content.size)
    resized = content.resize((max(1, round(content.width * scale)), max(1, round(content.height * scale))), Image.LANCZOS)
    canvas.alpha_composite(resized, ((canvas_px - resized.width) // 2, (canvas_px - resized.height) // 2))
    return canvas


def monochrome(img: Image.Image) -> Image.Image:
    """White silhouette from the alpha channel, for Android 13 themed icons."""
    white = Image.new("RGBA", img.size, (255, 255, 255, 0))
    white.putalpha(img.getchannel("A"))
    return white


def write(path: Path, img: Image.Image) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, optimize=True)


SYMBOL_TRIMMED = trimmed(SYMBOL)
LOGO_TRIMMED = trimmed(LOGO)

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
"""

LAUNCH_BACKGROUND_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Pre-Android 12 launch screen: brand navy with the MISHWAR logo centered.
     Generated by scripts/generate_brand_assets.py -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/launch_background" />
    <item>
        <bitmap
            android:gravity="center"
            android:src="@drawable/splash_logo" />
    </item>
</layer-list>
"""

V31_STYLES_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Android 12+ system splash screen (the OS draws this; it ignores windowBackground).
     Generated by scripts/generate_brand_assets.py -->
<resources>
    <style name="LaunchTheme" parent="@android:style/Theme.Black.NoTitleBar">
        <item name="android:windowSplashScreenBackground">@color/launch_background</item>
        <item name="android:windowSplashScreenAnimatedIcon">@drawable/splash_icon</item>
    </style>
    <style name="NormalTheme" parent="@android:style/Theme.Black.NoTitleBar">
        <item name="android:windowBackground">?android:colorBackground</item>
    </style>
</resources>
"""


def generate_android(app: str) -> None:
    res = ROOT / "apps" / app / "android" / "app" / "src" / "main" / "res"
    for name, factor in DENSITIES.items():
        mipmap = res / f"mipmap-{name}"
        # Legacy (pre-Android 8) icon: the full dark app icon, 48dp.
        write(mipmap / "ic_launcher.png", APP_ICON.resize((round(48 * factor),) * 2, Image.LANCZOS))
        # Adaptive icon layers: 108dp canvas, launcher masks to the inner ~72dp.
        layer_px = round(108 * factor)
        write(mipmap / "ic_launcher_background.png", gradient(layer_px, layer_px))
        foreground = fit_center(SYMBOL_TRIMMED, layer_px, 0.46)
        write(mipmap / "ic_launcher_foreground.png", foreground)
        write(mipmap / "ic_launcher_monochrome.png", monochrome(foreground))
        drawable = res / f"drawable-{name}"
        # Pre-Android 12 splash: logo with wordmark, ~200dp tall.
        logo_h = round(200 * factor)
        write(drawable / "splash_logo.png", LOGO_TRIMMED.resize(
            (round(LOGO_TRIMMED.width * logo_h / LOGO_TRIMMED.height), logo_h), Image.LANCZOS))
        # Android 12+ splash icon: 288dp canvas; the OS shows the inner 192dp circle.
        write(drawable / "splash_icon.png", fit_center(SYMBOL_TRIMMED, round(288 * factor), 0.5))

    (res / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
    (res / "mipmap-anydpi-v26" / "ic_launcher.xml").write_text(ADAPTIVE_XML, encoding="utf-8")
    for folder in ("drawable", "drawable-v21"):
        (res / folder / "launch_background.xml").write_text(LAUNCH_BACKGROUND_XML, encoding="utf-8")
    colors = res / "values" / "colors.xml"
    colors.write_text(
        f'<resources>\n    <color name="launch_background">{SPLASH_BG_HEX}</color>\n</resources>\n',
        encoding="utf-8",
    )
    for folder in ("values-v31", "values-night-v31"):
        (res / folder).mkdir(parents=True, exist_ok=True)
        (res / folder / "styles.xml").write_text(V31_STYLES_XML, encoding="utf-8")


def generate_web(app: str) -> None:
    web = ROOT / "apps" / app / "web"
    write(web / "favicon.png", APP_ICON.resize((64, 64), Image.LANCZOS))
    write(web / "icons" / "Icon-192.png", APP_ICON.resize((192, 192), Image.LANCZOS))
    write(web / "icons" / "Icon-512.png", APP_ICON.resize((512, 512), Image.LANCZOS))
    # Maskable icons: content must stay inside the central 80% circle.
    for size in (192, 512):
        write(web / "icons" / f"Icon-maskable-{size}.png", fit_center(SYMBOL_TRIMMED, size, 0.6, gradient(size, size)))
    write(web / "splash_logo.png", LOGO_TRIMMED.resize(
        (round(LOGO_TRIMMED.width * 360 / LOGO_TRIMMED.height), 360), Image.LANCZOS))


def generate_store() -> None:
    """Google Play listing graphics: 512x512 icon and 1024x500 feature graphic."""
    out = ROOT / "assets" / "store"
    write(out / "play_icon_512.png", APP_ICON.resize((512, 512), Image.LANCZOS).convert("RGB"))
    feature = gradient(1024, 500)
    logo_h = 300
    logo = LOGO_TRIMMED.resize((round(LOGO_TRIMMED.width * logo_h / LOGO_TRIMMED.height), logo_h), Image.LANCZOS)
    feature.alpha_composite(logo, ((1024 - logo.width) // 2, (500 - logo_h) // 2))
    write(out / "play_feature_graphic_1024x500.png", feature.convert("RGB"))


if __name__ == "__main__":
    for app_name in APPS:
        generate_android(app_name)
        generate_web(app_name)
        print(f"generated icons and splash for {app_name}")
    generate_store()
    print("generated Play Store graphics in assets/store/")
